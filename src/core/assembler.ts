import { AsmException, fail, type AsmError } from './errors'
import { evaluate, isRelocatable, linearize, type EvalContext, type Expr } from './expr'
import { encode } from './encoder'
import { bssBase, dataBase, STACK_TOP, TEXT_BASE } from './layout'
import { parse, type OperandAst, type Stmt } from './parser'
import type { Instruction, MemOperand, Operand, Scale } from './types'
import { fitsEither, type Size } from './util'

export type SectionName = 'text' | 'data' | 'bss'

export interface Section {
  name: SectionName
  start: number
  size: number
  /** Initial contents (zeros for .bss). */
  bytes: Uint8Array
}

export interface SymbolInfo {
  name: string
  value: bigint
  kind: 'label' | 'equ'
  section?: SectionName
  line: number
}

/** A data definition (db/dw/...) placed in memory; used by the memory view. */
export interface DataItemInfo {
  line: number
  address: number
  size: number
  unit: Size
}

export interface SourceMap {
  /** Address of the first byte generated by a source line. */
  lineToAddress: Map<number, number>
  /** Instruction start address → source line. */
  addressToLine: Map<number, number>
  /** Source line → instruction index (only for instruction lines). */
  lineToInstr: Map<number, number>
}

export interface Program {
  instructions: Instruction[]
  byAddress: Map<number, Instruction>
  sections: Record<SectionName, Section>
  entry: number
  stackTop: number
  symbols: SymbolInfo[]
  dataItems: DataItemInfo[]
  sourceMap: SourceMap
}

export interface AssembleResult {
  program: Program | null
  symbols: SymbolInfo[]
  sourceMap: SourceMap
  errors: AsmError[]
}

const MAX_PASSES = 20

interface PassResult {
  values: Map<string, bigint>
  labels: Set<string>
  symbols: SymbolInfo[]
  sizes: Record<SectionName, number>
  instructions: Instruction[]
  bytes: Record<SectionName, number[]>
  dataItems: DataItemInfo[]
  errors: AsmError[]
  newLong: boolean
  lineToAddress: Map<number, number>
}

function resolveMem(ast: Extract<OperandAst, { k: 'mem' }>, ctx: EvalContext, defaultRel: boolean): MemOperand {
  const lin = linearize(ast.expr, ctx)
  for (const r of lin.regs) if (r.reg.size !== 8) fail('address32', { name: r.reg.name })
  let base: MemOperand['base']
  let index: MemOperand['index']
  let scale: Scale = 1
  const regs = lin.regs
  const isScale = (c: bigint) => c === 1n || c === 2n || c === 4n || c === 8n
  if (regs.length === 1) {
    const { reg, coef } = regs[0]
    if (coef === 1n) base = reg
    else if (coef === 2n) {
      // NASM splits [r*2] into [r+r*1] (shorter, no disp32 needed)
      base = reg
      index = reg
    } else if (isScale(coef)) {
      index = reg
      scale = Number(coef) as Scale
    } else if (coef === 3n || coef === 5n || coef === 9n) {
      base = reg
      index = reg
      scale = Number(coef - 1n) as Scale
    } else fail('badAddress')
  } else if (regs.length === 2) {
    let [p, q] = regs
    if (p.coef !== 1n) [p, q] = [q, p]
    if (p.coef !== 1n || !isScale(q.coef)) fail('badAddress')
    base = p.reg
    index = q.reg
    scale = Number(q.coef) as Scale
  } else if (regs.length > 2) fail('badAddress')
  if (index && index.index === 4) {
    // RSP can never be an index register; swap if possible
    if (scale === 1 && base && base.index !== 4) [base, index] = [index, base]
    else fail('badAddress')
  }
  const rel = ast.rel ?? defaultRel
  return {
    k: 'mem',
    size: ast.size,
    base,
    index,
    scale,
    disp: lin.disp ?? 0n,
    ripRel: rel && !base && !index && isRelocatable(ast.expr, ctx),
    text: ast.text,
  }
}

function runPass(stmts: Stmt[], prev: Map<string, bigint>, prevLabels: Set<string>, prevSizes: Record<SectionName, number>, longJumps: Set<number>, final: boolean): PassResult {
  const starts: Record<SectionName, number> = {
    text: TEXT_BASE,
    data: dataBase(prevSizes.text),
    bss: 0,
  }
  starts.bss = bssBase(starts.data, prevSizes.data)
  const values = new Map<string, bigint>()
  const labels = new Set<string>(prevLabels)
  const symbols: SymbolInfo[] = []
  const offs: Record<SectionName, number> = { text: 0, data: 0, bss: 0 }
  const bytes: Record<SectionName, number[]> = { text: [], data: [], bss: [] }
  const instructions: Instruction[] = []
  const dataItems: DataItemInfo[] = []
  const errors: AsmError[] = []
  const lineToAddress = new Map<number, number>()
  let sec: SectionName = 'text'
  let defaultRel = false
  let newLong = false

  const here = () => BigInt(starts[sec] + offs[sec])
  const ctx = (): EvalContext => ({
    lookup: (n) => values.get(n) ?? prev.get(n),
    here: here(),
    start: BigInt(starts[sec]),
    final,
    isLabel: (n) => labels.has(n),
  })
  const define = (name: string, value: bigint, kind: 'label' | 'equ', line: number) => {
    if (values.has(name)) fail('duplicateSymbol', { name })
    values.set(name, value)
    symbols.push({ name, value, kind, section: kind === 'label' ? sec : undefined, line })
  }
  const emit = (b: number[]) => {
    if (sec === 'bss') {
      if (b.some((x) => x !== 0)) fail('resInData')
    }
    bytes[sec].push(...b)
    offs[sec] += b.length
  }

  stmts.forEach((st, si) => {
    try {
      switch (st.kind) {
        case 'section':
          sec = st.name
          return
        case 'default':
          defaultRel = st.rel
          return
        case 'global':
          return
        case 'label':
          labels.add(st.name)
          define(st.name, here(), 'label', st.line)
          return
        case 'equ': {
          const v = evaluate(st.expr, ctx())
          if (v === null && final) fail('notConstant', { name: st.name })
          define(st.name, v ?? 0n, 'equ', st.line)
          return
        }
        case 'res': {
          const n = evaluate(st.count, ctx())
          if (n === null) fail('notConstant', { name: 'res' })
          if (n < 0n || n > 0x100000n) fail('immOutOfRange', { value: String(n), size: 4 })
          if (!lineToAddress.has(st.line)) lineToAddress.set(st.line, Number(here()))
          const size = Number(n) * st.unit
          dataItems.push({ line: st.line, address: Number(here()), size, unit: st.unit })
          emit(new Array(size).fill(0))
          return
        }
        case 'data': {
          let times = 1
          if (st.times) {
            const t = evaluate(st.times, ctx())
            if (t === null) fail('notConstant', { name: 'times' })
            if (t < 0n || t > 0x100000n) fail('immOutOfRange', { value: String(t), size: 4 })
            times = Number(t)
          }
          const start = Number(here())
          if (!lineToAddress.has(st.line)) lineToAddress.set(st.line, start)
          const out: number[] = []
          for (let k = 0; k < times; k++) {
            for (const item of st.items) {
              if (item.k === 'str') {
                const padded = [...item.bytes]
                while (padded.length % st.unit) padded.push(0)
                out.push(...padded)
              } else {
                const c = { ...ctx(), here: BigInt(start + out.length) }
                const v = evaluate(item.e, c) ?? 0n
                if (final && !fitsEither(v, st.unit)) fail('immOutOfRange', { value: v.toString(), size: st.unit })
                let x = v
                for (let i = 0; i < st.unit; i++) {
                  out.push(Number(x & 0xffn))
                  x >>= 8n
                }
              }
            }
          }
          dataItems.push({ line: st.line, address: start, size: out.length, unit: st.unit })
          if (sec === 'bss' && out.some((x) => x !== 0)) fail('resInData')
          bytes[sec].push(...out)
          offs[sec] += out.length
          return
        }
        case 'instr': {
          if (sec !== 'text') fail('instrOutsideText')
          const address = Number(here())
          const c = ctx()
          const isBranch = ['jmp', 'jcc', 'call', 'loop'].includes(st.dec.op)
          const operands: Operand[] = st.operands.map((o): Operand => {
            if (o.k === 'reg') return { k: 'reg', reg: o.reg, text: o.text }
            if (o.k === 'mem') return resolveMem(o, c, defaultRel)
            const v = evaluate(o.expr as Expr, c)
            const reloc = isRelocatable(o.expr, c)
            if (v === null) return { k: 'imm', value: isBranch ? BigInt(address) : 0n, size: o.size, text: o.text, unresolved: true, reloc }
            return { k: 'imm', value: v, size: o.size, text: o.text, reloc }
          })
          let enc
          try {
            enc = encode({ op: st.dec.op, cond: st.dec.cond, mnemonic: st.mnemonic, operands }, { address, longJump: longJumps.has(si) })
          } catch (e) {
            if (final) throw e
            enc = { bytes: [0], opSize: undefined, jumpOutOfRange: false }
          }
          if (enc.jumpOutOfRange) {
            if (st.dec.op === 'loop') {
              if (final) fail('jumpOutOfRange')
            } else {
              longJumps.add(si)
              newLong = true
            }
          }
          const target = isBranch && operands[0]?.k === 'imm' ? Number(operands[0].value) : undefined
          instructions.push({
            id: instructions.length,
            op: st.dec.op,
            cond: st.dec.cond,
            mnemonic: st.mnemonic,
            operands,
            opSize: enc.opSize,
            line: st.line,
            text: st.text,
            address,
            length: enc.bytes.length,
            bytes: enc.bytes,
            target,
          })
          lineToAddress.set(st.line, address)
          bytes.text.push(...enc.bytes)
          offs.text += enc.bytes.length
          return
        }
      }
    } catch (e) {
      if (e instanceof AsmException) {
        if (final) errors.push({ line: st.line, code: e.code, params: e.params })
      } else throw e
    }
  })

  return { values, labels, symbols, sizes: { ...offs }, instructions, bytes, dataItems, errors, newLong, lineToAddress }
}

function sameMap(a: Map<string, bigint>, b: Map<string, bigint>): boolean {
  if (a.size !== b.size) return false
  for (const [k, v] of a) if (b.get(k) !== v) return false
  return true
}

function emptySourceMap(): SourceMap {
  return { lineToAddress: new Map(), addressToLine: new Map(), lineToInstr: new Map() }
}

/**
 * Assemble NASM source into a program image.
 * Pure function: no UI dependencies, safe to call on every keystroke.
 */
export function assemble(source: string): AssembleResult {
  const parsed = parse(source)
  const longJumps = new Set<number>()
  let prev = new Map<string, bigint>()
  let labels = new Set<string>()
  let prevSizes: Record<SectionName, number> = { text: 0, data: 0, bss: 0 }
  let stable = false
  for (let pass = 0; pass < MAX_PASSES; pass++) {
    const r = runPass(parsed.stmts, prev, labels, prevSizes, longJumps, false)
    labels = r.labels
    const same = sameMap(r.values, prev) && !r.newLong && r.sizes.text === prevSizes.text && r.sizes.data === prevSizes.data
    prev = r.values
    prevSizes = r.sizes
    if (same) {
      stable = true
      break
    }
  }
  const r = runPass(parsed.stmts, prev, labels, prevSizes, longJumps, true)
  const errors = [...parsed.errors, ...r.errors]
  if (!stable && !errors.length) errors.push({ line: 1, code: 'noConvergence' })
  errors.sort((a, b) => a.line - b.line)

  const sourceMap = emptySourceMap()
  sourceMap.lineToAddress = r.lineToAddress
  r.instructions.forEach((ins) => {
    sourceMap.addressToLine.set(ins.address, ins.line)
    sourceMap.lineToInstr.set(ins.line, ins.id)
  })

  if (!errors.length && r.instructions.length === 0) errors.push({ line: 1, code: 'noInstructions' })
  if (errors.length) return { program: null, symbols: r.symbols, sourceMap, errors }

  const textStart = TEXT_BASE
  const dataStart = dataBase(r.sizes.text)
  const bssStart = bssBase(dataStart, r.sizes.data)
  const sections: Record<SectionName, Section> = {
    text: { name: 'text', start: textStart, size: r.sizes.text, bytes: Uint8Array.from(r.bytes.text) },
    data: { name: 'data', start: dataStart, size: r.sizes.data, bytes: Uint8Array.from(r.bytes.data) },
    bss: { name: 'bss', start: bssStart, size: r.sizes.bss, bytes: new Uint8Array(r.sizes.bss) },
  }
  const entrySym = r.values.get('_start') ?? r.values.get('main')
  const program: Program = {
    instructions: r.instructions,
    byAddress: new Map(r.instructions.map((i) => [i.address, i])),
    sections,
    entry: entrySym !== undefined ? Number(entrySym) : r.instructions[0].address,
    stackTop: STACK_TOP,
    symbols: r.symbols,
    dataItems: r.dataItems,
    sourceMap,
  }
  return { program, symbols: r.symbols, sourceMap, errors: [] }
}
